def json_text(value):
    cleaned = ladder.clean_for_json(value)
    return json.dumps(cleaned, indent=1, sort_keys=True, allow_nan=False) + "\n"


def compact_rows_alternative_bytes(grid, frozen):
    """Size of the same bundle with the grid as 49 row objects per model.

    Measured for DECISIONS.md (columns vs rows); never written.
    """
    bundle = explorer_bundle(grid, frozen)
    for key in SIGNAL_ORDER:
        for name in buylist.MODEL_NAMES:
            bundle["signals"][key]["grid"][name] = grid["signals"][key]["models"][name]["grid"]
    return text_bytes(json_text(bundle))


def sha256_base64(data):
    digest = hashlib.sha256(data).digest()
    return base64.b64encode(digest).decode("ascii")


def text_bytes(text):
    return len(text.encode("utf-8"))


