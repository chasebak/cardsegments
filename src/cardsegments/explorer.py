def label_problems(grid, frozen):
    """Every source and every signal must carry a SYNTHETIC label.

    Why: the real-data page waits on the feed terms; a block without the
    label could be a real-data run, so the build refuses it rather than
    publishing it. Failure mode: a mislabelled real run passes this check;
    the private deny-list check before a push is the second layer.
    """
    problems = []
    if not str(grid.get("label", "")).startswith(SYNTHETIC_PREFIX):
        problems.append("%s is not labelled %s" % (buylist.GRID_PATH_REL, SYNTHETIC_PREFIX))
    if not str(frozen.get("label", "")).startswith(SYNTHETIC_PREFIX):
        problems.append("%s is not labelled %s" % (ladder_report.FROZEN_PATH_REL,
                                                   SYNTHETIC_PREFIX))
    return problems


def frozen_match_problems(grid, frozen):
    """The recomputed grid must reproduce the frozen ladder's t* = 2/3 buy lists.

    Rule: at every signal, the default cost setting's exact-t* TP/FP/FN/TN
    for the model and for velocity equal ladder_frozen.json's kpi
    model_confusion / velocity_confusion, and the parked-delta value and CI
    are identical. Failure mode: a ladder change that alters the logistic
    fits would make the page and the README headline disagree; this check
    stops the build instead.
    """
    problems = []
    pairs = ((ladder.HEADLINE_MODEL, "model_confusion"),
             (ladder.BASELINE_CLASSIFIER, "velocity_confusion"))
    for key in SIGNAL_ORDER:
        kpi = frozen["signals"][key]["kpi"]
        setting = grid["signals"][key]["cost_settings"][DEFAULT_SETTING]
        if setting["t_star"] != kpi["t_star"]:
            problems.append("signal %s: t* differs from the frozen run" % key)
        for name, frozen_key in pairs:
            cell = setting["models"][name]["at_t_star"]
            frozen_cell = kpi[frozen_key]
            for part in ("tp", "fp", "fn", "tn"):
                if cell[part] != frozen_cell[part]:
                    problems.append("signal %s: %s %s differs from the frozen run"
                                    % (key, name, part))
        for part in CI_KEYS:
            if setting["delta_parked"][part] != kpi["delta_parked"][part]:
                problems.append("signal %s: delta_parked %s differs from the frozen run"
                                % (key, part))
    return problems


