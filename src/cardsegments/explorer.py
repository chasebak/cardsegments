def expected_outputs(root=None):
    """{repo-relative path: full expected text} for every generated file.

    Raises ValueError when a source is unlabelled or the grid does not
    reproduce the frozen run, so nothing stale or unlabelled is written.
    """
    if root is None:
        root = repo_root()
    grid, frozen = load_sources(root)
    problems = label_problems(grid, frozen) + frozen_match_problems(grid, frozen)
    if problems:
        raise ValueError("; ".join(problems))
    explorer_text = json_text(explorer_bundle(grid, frozen))
    page_bytes = text_bytes(explorer_text)
    rows_bytes = compact_rows_alternative_bytes(grid, frozen)
    meta = {"generated_by": GENERATED_BY, "chartjs_version": CHART_JS_VERSION,
            "chartjs_tag": CHART_JS_TAG, "tokens_css_sha256_base64": TOKENS_SHA256_B64,
            "data_budget_bytes": DATA_BUDGET_BYTES,
            "data_bytes": {EXPLORER_PATH.rsplit("/", 1)[1]: page_bytes},
            "sources": [buylist.GRID_PATH_REL, ladder_report.FROZEN_PATH_REL]}
    outputs = {EXPLORER_PATH: explorer_text, META_PATH: json_text(meta)}
    with open(os.path.join(root, "README.md")) as handle:
        readme = handle.read()
    outputs["README.md"] = ladder_report.replace_block(readme, README_BLOCK, readme_block(grid))
    with open(os.path.join(root, "DECISIONS.md")) as handle:
        decisions = handle.read()
    outputs["DECISIONS.md"] = ladder_report.replace_block(
        decisions, DECISIONS_BLOCK, decisions_block(grid, frozen, page_bytes, rows_bytes))
    with open(os.path.join(root, "docs", "METHOD.md")) as handle:
        method = handle.read()
    outputs["docs/METHOD.md"] = ladder_report.replace_block(method, METHOD_BLOCK,
                                                            assumptions_table())
    return outputs


def collect_keys(value, found):
    """Every dict key anywhere inside value, added to the set found."""
    if isinstance(value, dict):
        items = list(value.items())
        for key, item in items:
            found.add(key)
            collect_keys(item, found)
    elif isinstance(value, list):
        for item in value:
            collect_keys(item, found)
    return found


def longest_list(value):
    """Length of the longest list anywhere inside value."""
    longest = 0
    if isinstance(value, dict):
        children = list(value.values())
    elif isinstance(value, list):
        longest = len(value)
        children = value
    else:
        children = []
    for child in children:
        child_longest = longest_list(child)
        longest = max(longest, child_longest)
    return longest


def unlabelled_blocks(bundle):
    """Signal blocks whose label is missing, and a top label not SYNTHETIC."""
    problems = []
    if not str(bundle.get("label", "")).startswith(SYNTHETIC_PREFIX):
        problems.append("top label")
    signals = bundle.get("signals", {})
    keys = sorted(signals.keys())
    for key in keys:
        if not signals[key].get("label"):
            problems.append("signal %s" % key)
    return problems


def bundle_problems(outputs):
    """Allowlist, banned-key, label, list-length and size problems of the page data."""
    problems = []
    allowed = allowed_keys()
    total_bytes = 0
    for path in DATA_PATHS:
        if path not in outputs:
            problems.append("%s: missing from the build" % path)
            continue
        text = outputs[path]
        total_bytes += text_bytes(text)
        value = json.loads(text)
        keys = collect_keys(value, set())
        unexpected = sorted(keys - allowed[path])
        if unexpected:
            problems.append("%s: keys outside the allowlist: %s" % (path, unexpected))
        banned = sorted(keys & set(BANNED_KEYS))
        if banned:
            problems.append("%s: card-level keys: %s" % (path, banned))
        longest = longest_list(value)
        if longest > MAX_LIST_LENGTH:
            problems.append("%s: a list of %d entries (max %d)" % (path, longest,
                                                                   MAX_LIST_LENGTH))
        if path == EXPLORER_PATH:
            unlabelled = unlabelled_blocks(value)
            if unlabelled:
                problems.append("%s: unlabelled blocks: %s" % (path, unlabelled))
    if total_bytes > DATA_BUDGET_BYTES:
        problems.append("page data are %d bytes (budget %d)" % (total_bytes, DATA_BUDGET_BYTES))
    return problems


def static_problems(root):
    """Problems with the page's fixed files (tokens copy, .nojekyll, script tag)."""
    problems = []
    tokens_path = os.path.join(root, TOKENS_PATH)
    if not os.path.isfile(tokens_path):
        problems.append("%s is missing" % TOKENS_PATH)
    else:
        with open(tokens_path, "rb") as handle:
            tokens = handle.read()
        if sha256_base64(tokens) != TOKENS_SHA256_B64:
            problems.append("%s is not the page kit's tokens.css" % TOKENS_PATH)
    if not os.path.isfile(os.path.join(root, NOJEKYLL_PATH)):
        problems.append("%s is missing" % NOJEKYLL_PATH)
    index_path = os.path.join(root, INDEX_PATH)
    if not os.path.isfile(index_path):
        problems.append("%s is missing" % INDEX_PATH)
    else:
        with open(index_path) as handle:
            index_text = handle.read()
        if index_text.count(CHART_JS_TAG) != 1:
            problems.append("%s lacks the pinned Chart.js tag" % INDEX_PATH)
    if not os.path.isfile(os.path.join(root, APP_PATH)):
        problems.append("%s is missing" % APP_PATH)
    return problems


def check(root=None, outputs=None):
    """List of problems; empty means every generated file is fresh."""
    if root is None:
        root = repo_root()
    if outputs is None:
        try:
            outputs = expected_outputs(root)
        except ValueError as error:
            return [str(error)]
    problems = bundle_problems(outputs)
    paths = sorted(outputs.keys())
    for rel_path in paths:
        full_path = os.path.join(root, rel_path)
        if not os.path.isfile(full_path):
            problems.append("%s is missing" % rel_path)
            continue
        with open(full_path) as handle:
            committed = handle.read()
        if committed != outputs[rel_path]:
            problems.append("%s is stale (run %s)" % (rel_path, GENERATED_BY))
    problems.extend(static_problems(root))
    return problems


def stale_files(root=None):
    """Generated files whose committed text differs from a fresh build."""
    if root is None:
        root = repo_root()
    outputs = expected_outputs(root)
    stale = []
    paths = sorted(outputs.keys())
    for rel_path in paths:
        full_path = os.path.join(root, rel_path)
        if not os.path.isfile(full_path):
            stale.append(rel_path)
            continue
        with open(full_path) as handle:
            current = handle.read()
        if current != outputs[rel_path]:
            stale.append(rel_path)
    return stale


def write(root=None):
    if root is None:
        root = repo_root()
    outputs = expected_outputs(root)
    problems = bundle_problems(outputs)
    if problems:
        return problems
    paths = sorted(outputs.keys())
    for rel_path in paths:
        full_path = os.path.join(root, rel_path)
        os.makedirs(os.path.dirname(full_path), exist_ok=True)
        with open(full_path, "w") as handle:
            handle.write(outputs[rel_path])
        print("wrote", rel_path)
    return []
