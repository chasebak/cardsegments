def all_cells(grid):
    """(signal key, setting, model name, regret block) for every cell."""
    cells = []
    for key in SIGNAL_ORDER:
        for setting in grid["signals"][key]["cost_settings"]:
            for name in buylist.MODEL_NAMES:
                cells.append((key, setting, name, setting["models"][name]))
    return cells


def frozen_fit_seconds(frozen):
    total = 0.0
    for key in SIGNAL_ORDER:
        block = frozen["signals"][key]
        rows = block["classification"] + block["regression"]
        for row in rows:
            seconds = row.get("fit_seconds")
            if seconds is not None:
                total += seconds
    return total


def recompute_seconds(grid):
    total = 0.0
    for key in SIGNAL_ORDER:
        total += grid["signals"][key]["seconds"]["total"]
    return total


def ci_excludes_zero_count(grid, key):
    excluded = 0
    for setting in grid["signals"][key]["cost_settings"]:
        delta = setting["delta_parked"]
        if delta["ci_low"] is not None and delta["ci_low"] > 0.0:
            excluded += 1
    return excluded


def snapped_cell(grid, key, setting_index, name):
    """The grid row nearest to t* (what snapping t* to the slider would show)."""
    thresholds = grid_thresholds(grid)
    setting = grid["signals"][key]["cost_settings"][setting_index]
    index = nearest_index(thresholds, setting["t_star"])
    return grid["signals"][key]["models"][name]["grid"][index]


def small_list_cells(grid, min_n=None):
    """How many grid cells hold a buy list under the n >= 50 floor.

    Counts (signal, list, threshold) cells with 0 < n_flagged < min_n (an
    empty list has no parked rate to disclose) and finds the smallest
    non-empty list. Failure mode: it counts list size only; TP or FP
    counts inside a large list can still be small.
    """
    if min_n is None:
        min_n = report.MIN_CELL_N
    n_small = 0
    n_cells = 0
    smallest = None
    for key in SIGNAL_ORDER:
        for name in buylist.MODEL_NAMES:
            rows = grid["signals"][key]["models"][name]["grid"]
            for row in rows:
                n_cells += 1
                flagged = row["n_flagged"]
                if flagged == 0:
                    continue
                if flagged < min_n:
                    n_small += 1
                if smallest is None or flagged < smallest["n_flagged"]:
                    smallest = {"n_flagged": flagged, "key": key, "name": name,
                                "threshold": row["threshold"]}
    return {"n_small": n_small, "n_cells": n_cells, "smallest": smallest}


