def t_star_text(t_star):
    """'2/3' for 0.6666666667: the cost ratio as a small fraction."""
    fraction = Fraction(t_star).limit_denominator(20)
    return "%d/%d" % (fraction.numerator, fraction.denominator)


def nearest_index(thresholds, value):
    """Index of the grid point closest to value (the slider's starting stop)."""
    best_index = 0
    best_gap = None
    position = 0
    for threshold in thresholds:
        gap = abs(threshold - value)
        if best_gap is None or gap < best_gap:
            best_gap = gap
            best_index = position
        position += 1
    return best_index


def grid_thresholds(grid):
    rows = grid["signals"][SIGNAL_ORDER[0]]["models"][ladder.HEADLINE_MODEL]["grid"]
    thresholds = []
    for row in rows:
        thresholds.append(row["threshold"])
    return thresholds


def setting_name(m, h, t_star):
    return "m %.2f · h %.2f → t* = %s" % (m, h, t_star_text(t_star))


def settings_block(grid, thresholds):
    first = grid["signals"][SIGNAL_ORDER[0]]["cost_settings"]
    settings = []
    for setting in first:
        settings.append({"m": setting["m"], "h": setting["h"], "t_star": setting["t_star"],
                         "t_star_text": t_star_text(setting["t_star"]),
                         "name": setting_name(setting["m"], setting["h"], setting["t_star"]),
                         "nearest_index": nearest_index(thresholds, setting["t_star"])})
    return settings


def grid_columns(rows):
    """49 grid rows -> one 49-entry list per column (DECISIONS: smaller JSON)."""
    columns = {}
    for column in GRID_COLUMNS:
        columns[column] = []
    for row in rows:
        for column in GRID_COLUMNS:
            columns[column].append(row[column])
    return columns


def page_setting(setting):
    models = {}
    for name in buylist.MODEL_NAMES:
        source = setting["models"][name]
        cell = {}
        for key in CELL_KEYS:
            cell[key] = source["at_t_star"][key]
        for key in REGRET_KEYS:
            cell[key] = source[key]
        cell["cost_curve"] = source["grid_costs"]
        models[name] = cell
    delta = {}
    for key in CI_KEYS:
        delta[key] = setting["delta_parked"][key]
    return {"models": models, "delta_parked": delta}


def page_signal(key, grid_block, frozen_block):
    dataset = frozen_block["dataset"]
    kpi = frozen_block["kpi"]
    grid_models = {}
    for name in buylist.MODEL_NAMES:
        grid_models[name] = grid_columns(grid_block["models"][name]["grid"])
    settings = []
    for setting in grid_block["cost_settings"]:
        settings.append(page_setting(setting))
    delta_auc = {}
    for part in CI_KEYS:
        delta_auc[part] = kpi["delta_auc"][part]
    return {"label": ladder_report.SIGNAL_LABELS[key],
            "short": ladder_report.SIGNAL_SHORT[key],
            "n_rows": dataset["n_rows"], "n_groups": dataset["n_groups"],
            "base_rate": dataset["base_rate"], "n_sellers": grid_block["n_sellers"],
            "buy_everything_parked": grid_block["buy_everything_parked"],
            "delta_auc": delta_auc, "auc_beats_velocity": kpi["auc_beats_velocity"],
            "grid": grid_models, "settings": settings}


